/**
 * E1：从记忆内容里认出日期（2026-09-18 真机：7 月已结束的一次出差筹备被当成当前主线）。
 * 写法取自用户真实资料的日期分布：「N月NN日」「N月NN日至NN日」「NNNN年N月NN日」、
 * 只写日的「NN日」（沿用前面的月份）。宁可少认，不能认错。
 */
import { describe, expect, it } from 'vitest';
import { mentionedDays, pastEventDay } from '../../src/memory/temporal.js';

const REC = '2026-09-13T08:00:00.000Z'; // 导入分析那天，不是事情发生那天

describe('认出内容里的日期', () => {
  it.each([
    ['7月26日上午活动的详细时间表已确定', ['2026-07-26']],
    ['需在7月20日至26日完成整体行程安排', ['2026-07-20', '2026-07-26']],
    ['新店开业筹备定于2026年7月20日至7月26日', ['2026-07-20', '2026-07-26']],
    ['7月25日到达，26日上午参观', ['2026-07-25', '2026-07-26']],
    ['7月20日到8月2日在外地', ['2026-07-20', '2026-08-02']],
    ['截止 2026-07-31 提交', ['2026-07-31']],
    ['7月26号开业，至28号收尾', ['2026-07-26', '2026-07-28']],
  ])('%s', (text, expected) => {
    expect(mentionedDays(text, REC)).toEqual(expected);
  });

  it.each([
    ['下周三下午去看牙'],
    ['7月下旬去一趟'],
    ['回复一律用中文'],
    ['住在3号楼'],
    ['版本号 1.2.3 已发布'],
    ['2月30日这种不存在的日期'],
  ])('不认：%s', (text) => {
    expect(mentionedDays(text, REC)).toEqual([]);
  });

  it('没写年份：取离「记下这条」最近的那一年', () => {
    expect(mentionedDays('1月5日开会', '2026-12-20T00:00:00Z')).toEqual(['2027-01-05']);
    expect(mentionedDays('12月28日开会', '2026-01-05T00:00:00Z')).toEqual(['2025-12-28']);
  });
});

describe('这件事过没过去', () => {
  const today = new Date(2026, 8, 18); // 2026-09-18（本地）

  it('区间看结束那天：7 月 20—26 日的行程到 9 月已经过去', () => {
    expect(pastEventDay('需在7月20日至26日完成整体行程安排', REC, today)).toBe('2026-07-26');
  });

  it('提到多个日期看最晚那天：推迟到还没到的日子就不算过去', () => {
    expect(pastEventDay('原定7月26日开业，推迟到10月8日', REC, today)).toBeNull();
  });

  it('就是今天的事不算过去', () => {
    expect(pastEventDay('9月18日交周报', REC, today)).toBeNull();
  });

  it('没有日期的不判断', () => {
    expect(pastEventDay('长期做一个本地优先的个人助手', REC, today)).toBeNull();
  });
});
